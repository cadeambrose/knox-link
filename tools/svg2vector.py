"""Turns the <symbol> icons in web/index.html into Android VectorDrawable files, so the web app
and the Android app share one icon set. Run: python tools/svg2vector.py"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "web", "index.html")
OUT = os.path.join(ROOT, "android", "res", "drawable")


def attrs(tag):
    return dict(re.findall(r'([\w-]+)="([^"]*)"', tag))


def rect_path(a):
    x, y = float(a.get("x", 0)), float(a.get("y", 0))
    w, h = float(a["width"]), float(a["height"])
    rx = float(a.get("rx", 0))
    rx = min(rx, w / 2, h / 2)
    if rx <= 0:
        return f"M{x},{y}h{w}v{h}h{-w}z"
    return (f"M{x + rx},{y}h{w - 2 * rx}a{rx},{rx} 0 0 1 {rx},{rx}v{h - 2 * rx}"
            f"a{rx},{rx} 0 0 1 {-rx},{rx}h{-(w - 2 * rx)}a{rx},{rx} 0 0 1 {-rx},{-rx}"
            f"v{-(h - 2 * rx)}a{rx},{rx} 0 0 1 {rx},{-rx}z")


def circle_path(a):
    cx, cy, r = float(a["cx"]), float(a["cy"]), float(a["r"])
    return f"M{cx - r},{cy}a{r},{r} 0 1 0 {2 * r},0a{r},{r} 0 1 0 {-2 * r},0z"


def main():
    html = open(SRC, encoding="utf-8").read()
    os.makedirs(OUT, exist_ok=True)
    count = 0
    for m in re.finditer(r'<symbol id="i-([\w-]+)" viewBox="0 0 24 24">(.*?)</symbol>', html, re.S):
        name, body = m.group(1).replace("-", "_"), m.group(2)
        paths = []
        for tm in re.finditer(r"<(path|rect|circle)\b([^>]*)/?>", body):
            kind, a = tm.group(1), attrs(tm.group(2))
            if kind == "path":
                d = a["d"]
            elif kind == "rect":
                d = rect_path(a)
            else:
                d = circle_path(a)
            filled = a.get("fill") == "currentColor"
            transform = a.get("transform")
            group_open = group_close = ""
            if transform:
                rm = re.match(r"rotate\((-?[\d.]+) ([\d.]+) ([\d.]+)\)", transform)
                if rm:
                    group_open = (f'    <group android:rotation="{rm.group(1)}" android:pivotX="{rm.group(2)}" '
                                  f'android:pivotY="{rm.group(3)}">\n')
                    group_close = "    </group>\n"
            if filled:
                p = f'        <path android:fillColor="#FFFFFFFF" android:pathData="{d}"/>\n'
            else:
                p = (f'        <path android:fillColor="#00000000" android:strokeColor="#FFFFFFFF" '
                     f'android:strokeWidth="1.8" android:strokeLineCap="round" android:strokeLineJoin="round" '
                     f'android:pathData="{d}"/>\n')
            paths.append(group_open + p + group_close)
        xml = ('<?xml version="1.0" encoding="utf-8"?>\n'
               '<!-- generated by tools/svg2vector.py from web/index.html -->\n'
               '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
               '    android:width="24dp" android:height="24dp"\n'
               '    android:viewportWidth="24" android:viewportHeight="24">\n'
               + "".join(paths) + "</vector>\n")
        with open(os.path.join(OUT, f"ic_{name}.xml"), "w", encoding="utf-8", newline="\n") as f:
            f.write(xml)
        count += 1
    print(f"{count} icons written to {OUT}")


if __name__ == "__main__":
    sys.exit(main())
